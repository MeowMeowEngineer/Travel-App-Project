"""IndexNow 알림: production 빌드에서만, site.json에 site_url·indexnow_key가 있을 때만. 테스트에서는 절대 보내지 않는다."""
import io
import json
import shutil
import urllib.error
from pathlib import Path

import pytest

from pipeline.build import build
from tools import indexnow

KEY = "0123456789abcdef0123456789abcdef"
SITE = "https://gunsan.example"
PROD_ROBOTS = ("User-agent: Bingbot\nAllow: /\n\n# 학습 전용\nUser-agent: GPTBot\nUser-agent: CCBot\nDisallow: /\n\n"
               "User-agent: *\nAllow: /\n\nSitemap: https://gunsan.example/sitemap.xml\n")
PREVIEW_ROBOTS = "# 미리보기\nUser-agent: *\nDisallow: /\n"


@pytest.fixture(autouse=True)
def no_network(monkeypatch):
    def refuse(*args, **kwargs):
        raise AssertionError("tests must not send IndexNow requests")
    monkeypatch.setattr(indexnow.urllib.request, "urlopen", refuse)


def sitemap(*rows: tuple[str, str]) -> str:
    body = "\n".join(f"  <url><loc>{loc}</loc><lastmod>{lastmod}</lastmod></url>" for loc, lastmod in rows)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            f"{body}\n</urlset>\n")


def make_site(tmp_path: Path, robots=PROD_ROBOTS, meta="index, follow", site_url=SITE, key=KEY,
              rows=((f"{SITE}/", "2026-10-01"), (f"{SITE}/places/%EB%8F%99%EA%B5%AD%EC%82%AC/", "2026-10-20"))):
    out, data = tmp_path / "dist-prod", tmp_path / "data"
    out.mkdir()
    data.mkdir()
    (out / ".webforai-build").write_text("generated by pipeline.build\n", "utf-8")
    (out / "robots.txt").write_text(robots, "utf-8")
    (out / "index.html").write_text(f'<!doctype html><head><meta name="robots" content="{meta}"></head>', "utf-8")
    (out / "sitemap.xml").write_text(sitemap(*rows), "utf-8")
    site = {"site_url": site_url, "site_name": "t"}
    if key is not None:
        site["indexnow_key"] = key
    (data / "site.json").write_text(json.dumps(site), "utf-8")
    return out, data


def run(out: Path, data: Path, *extra: str) -> int:
    return indexnow.main(["--out", str(out), "--data", str(data), *extra])


def test_robots_group_parsing():
    assert indexnow.robots_blocks_all(PREVIEW_ROBOTS)
    assert not indexnow.robots_blocks_all(PROD_ROBOTS)  # only the training bots are disallowed


def test_dry_run_writes_key_file_and_prints_payload(tmp_path, capsys):
    out, data = make_site(tmp_path)
    assert run(out, data) == 0
    assert (out / f"{KEY}.txt").read_text("utf-8") == KEY
    text = capsys.readouterr().out
    payload = json.loads(text[text.index("{"):text.rindex("}") + 1])
    assert payload == {"host": "gunsan.example", "key": KEY, "keyLocation": f"{SITE}/{KEY}.txt",
                       "urlList": [f"{SITE}/", f"{SITE}/places/%EB%8F%99%EA%B5%AD%EC%82%AC/"]}
    assert "--send" in text


def test_since_keeps_recent_urls_only(tmp_path, capsys):
    out, data = make_site(tmp_path)
    assert run(out, data, "--since", "2026-10-10") == 0
    assert f'"{SITE}/"' not in capsys.readouterr().out


@pytest.mark.parametrize("kwargs, message", [
    ({"robots": PREVIEW_ROBOTS}, "Disallow: /"),
    ({"meta": "noindex, nofollow"}, "noindex"),
    ({"site_url": ""}, "site_url이 비어"),
    ({"key": None}, "indexnow_key가 없습니다"),
    ({"key": "short"}, "형식"),
    ({"rows": (("/places/x/", "2026-10-01"),)}, "도메인이 아닌 URL"),   # built while site_url was empty
])
def test_refuses_unless_production_and_configured(tmp_path, capsys, kwargs, message):
    out, data = make_site(tmp_path, **kwargs)
    assert run(out, data) == 1
    assert message in capsys.readouterr().err
    assert sorted(p.name for p in out.glob("*.txt")) == ["robots.txt"]  # no key file written


def test_refuses_folder_not_built_by_pipeline(tmp_path, capsys):
    out, data = make_site(tmp_path)
    (out / ".webforai-build").unlink()
    assert run(out, data) == 1
    assert "pipeline.build" in capsys.readouterr().err


def test_send_posts_standard_body_and_shows_provider_reply(tmp_path, monkeypatch, capsys):
    out, data = make_site(tmp_path)
    sent = []
    monkeypatch.setattr(indexnow, "post_json", lambda url, payload: sent.append((url, payload)) or (202, "Accepted"))
    assert run(out, data, "--send") == 0
    assert sent[0][0] == "https://api.indexnow.org/indexnow"
    assert set(sent[0][1]) == {"host", "key", "keyLocation", "urlList"} and len(sent[0][1]["urlList"]) == 2
    assert "202 Accepted" in capsys.readouterr().out
    monkeypatch.setattr(indexnow, "post_json", lambda url, payload: (403, "Forbidden key not valid"))
    assert run(out, data, "--send") == 1
    assert "403 Forbidden key not valid" in capsys.readouterr().out


def test_post_json_returns_provider_error_body(monkeypatch):
    def fake(request, timeout):
        assert request.get_method() == "POST" and json.loads(request.data) == {"a": 1}
        raise urllib.error.HTTPError(request.full_url, 422, "Unprocessable Entity", {}, io.BytesIO(b"URLs not on host"))
    monkeypatch.setattr(indexnow.urllib.request, "urlopen", fake)
    assert indexnow.post_json("https://api.indexnow.org/indexnow", {"a": 1}) == (422, "Unprocessable Entity URLs not on host")


def test_real_builds_preview_refused_production_accepted(tmp_path, capsys):
    data = tmp_path / "data"
    shutil.copytree(Path(__file__).resolve().parents[1] / "data" / "sample", data)
    site = json.loads((data / "site.json").read_text("utf-8"))
    site.update(site_url=SITE, indexnow_key=KEY)
    (data / "site.json").write_text(json.dumps(site, ensure_ascii=False), "utf-8")
    build(data, tmp_path / "preview", "preview")
    assert run(tmp_path / "preview", data) == 1
    build(data, tmp_path / "prod", "production")
    capsys.readouterr()
    assert run(tmp_path / "prod", data) == 0
    text = capsys.readouterr().out
    assert f'"{SITE}/"' in text and (tmp_path / "prod" / f"{KEY}.txt").exists()
